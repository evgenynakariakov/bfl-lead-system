from __future__ import annotations

from datetime import datetime
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Cm, Pt


PROJECT_DIR = Path(r"D:\bfl_system_complete")
REPORT_DIR = PROJECT_DIR / "отчет"
OUT_FILE = REPORT_DIR / "Отчет_Тестовое_задание_БФЛ_финал.docx"


def set_document_style(doc: Document) -> None:
    section = doc.sections[0]
    section.page_width = Cm(21.0)
    section.page_height = Cm(29.7)
    section.left_margin = Cm(2.2)
    section.right_margin = Cm(1.8)
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(2.0)

    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    normal.font.size = Pt(12)


def add_title(doc: Document) -> None:
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run(
        "Отчет по тестовому заданию\n"
        "на позицию Junior Traffic Engineer\n"
        "Проект: BFL Lead System"
    )
    run.bold = True
    run.font.size = Pt(16)

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    subtitle.add_run(
        f"Дата подготовки: {datetime.now().strftime('%d.%m.%Y')}\n"
        "Технологический стек: Python 3.13, PostgreSQL, Playwright, Telegram Bot API, Streamlit"
    ).font.size = Pt(11)

    doc.add_paragraph("")


def add_section_heading(doc: Document, text: str) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(13)


def add_body(doc: Document, text: str) -> None:
    p = doc.add_paragraph(text.strip())
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.first_line_indent = Cm(1.25)
    p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.line_spacing = 1.5


def add_figure(doc: Document, image_path: Path, caption: str, width_cm: float = 16.0) -> None:
    if not image_path.exists():
        add_body(
            doc,
            f"Иллюстрация «{caption}» не была вставлена автоматически, так как файл {image_path.name} "
            "не найден в папке отчета.",
        )
        return

    fig = doc.add_paragraph()
    fig.alignment = WD_ALIGN_PARAGRAPH.CENTER
    fig.add_run().add_picture(str(image_path), width=Cm(width_cm))

    cap = doc.add_paragraph(caption)
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.runs[0].italic = True
    cap.runs[0].font.size = Pt(11)
    cap.paragraph_format.space_after = Pt(10)


