def configure_doc(doc: Document) -> None:
    section = doc.sections[0]
    section.page_width = Cm(21.0)
    section.page_height = Cm(29.7)
    section.left_margin = Cm(2.2)
    section.right_margin = Cm(1.8)
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(2.0)

    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    style.font.size = Pt(12)


def add_heading(doc: Document, text: str, size: int = 13) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(size)


def add_text(doc: Document, text: str) -> None:
    p = doc.add_paragraph(text.strip())
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.first_line_indent = Cm(1.25)
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_after = Pt(8)


def add_figure(doc: Document, image_path: Path, caption: str, width_cm: float = 13.2) -> None:
    if image_path.exists():
        fig = doc.add_paragraph()
        fig.alignment = WD_ALIGN_PARAGRAPH.CENTER
        fig.add_run().add_picture(str(image_path), width=Cm(width_cm))
        cp = doc.add_paragraph(caption)
        cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        cp.runs[0].italic = True
        cp.runs[0].font.size = Pt(11)
    else:
        add_text(doc, f"Иллюстрация «{caption}» не вставлена автоматически, файл {image_path.name} не найден.")


